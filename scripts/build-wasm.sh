#!/usr/bin/env bash
# Builds the WebAssembly library and embeds it in js/wasm.mjs and go/somtumpp/somtum_pp.wasm.
set -euo pipefail
cd "$(dirname "$0")/.."
cargo build --profile release-wasm --target wasm32-unknown-unknown --lib
wasm=target/wasm32-unknown-unknown/release-wasm/somtum_pp.wasm
cp "$wasm" go/somtumpp/somtum_pp.wasm
{ echo "// Generated by scripts/build-wasm.sh from $(git rev-parse --short HEAD 2>/dev/null || echo unknown). Do not edit."
  printf 'export const WASM_BASE64 =\n    "%s";\n' "$(base64 -w0 "$wasm")"; } > js/wasm.mjs
sha256sum "$wasm" | cut -d' ' -f1 > js/wasm.sha256
cp js/wasm.sha256 go/somtumpp/somtum_pp.wasm.sha256
echo "wasm $(stat -c%s "$wasm") bytes, sha256 $(cat js/wasm.sha256)"
